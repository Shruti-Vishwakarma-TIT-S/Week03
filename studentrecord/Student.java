package com.datastructures.linkedlist.studentrecord;

// Define the Student class to store student information
class Student {
    int rollNumber;
    String name;
    int age;
    String grade;

    // Constructor to initialize student record
    public Student(int rollNumber, String name, int age, String grade) {
        this.rollNumber = rollNumber;
        this.name = name;
        this.age = age;
        this.grade = grade;
    }
}


